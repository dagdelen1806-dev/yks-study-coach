/**
 * MySQL (Railway) → PostgreSQL (Supabase) veri kopyalama.
 *
 *   SOURCE_MYSQL_URL=mysql://...  TARGET_PG_URL=postgres://...  npx tsx scripts/pg-migration/copy-data.ts [--dry-run]
 *
 * - Hedef şema önceden kurulmuş olmalı (DATABASE_URL=<hedef> npx drizzle-kit migrate) ve tablolar BOŞ olmalı;
 *   dolu tablo görürse hiçbir şey yazmadan durur (yanlışlıkla iki kez çalıştırmaya karşı).
 * - Tablo ve kolon listesi drizzle/schema.ts'den okunur; kaynakta olmayan kolon (ör. yeni eklenmiş) varsayılanını alır.
 * - id'ler korunur; sonunda her tablonun kimlik (identity) sayacı en büyük id'ye ayarlanır.
 * - Zaman damgaları UTC olarak okunur (Vercel'de süreç UTC çalıştığı için MySQL'e UTC yazıldı).
 * - Sonunda her tablo için satır sayıları karşılaştırılır; fark varsa çıkış kodu 1.
 */
import { getTableConfig, type PgTable } from "drizzle-orm/pg-core";
import mysql from "mysql2/promise";
import postgres from "postgres";
import * as schema from "../../drizzle/schema";

const BATCH = 500;
const dryRun = process.argv.includes("--dry-run");
const sourceUrl = process.env.SOURCE_MYSQL_URL;
const targetUrl = process.env.TARGET_PG_URL;
if (!sourceUrl || !targetUrl) {
  console.error("SOURCE_MYSQL_URL ve TARGET_PG_URL gerekli.");
  process.exit(1);
}

const tables = Object.values(schema)
  .filter((value): value is PgTable => typeof value === "object" && value !== null && Symbol.for("drizzle:IsDrizzleTable") in value)
  .map((table) => {
    const config = getTableConfig(table);
    return { name: config.name, columns: config.columns.map((column) => column.name), hasId: config.columns.some((column) => column.name === "id") };
  });

async function main() {
  const source = await mysql.createConnection({ uri: sourceUrl, timezone: "Z", dateStrings: false, supportBigNumbers: true, bigNumberStrings: true });
  await source.query("SET time_zone = '+00:00'");
  const target = postgres(targetUrl!, { max: 1, prepare: false, onnotice: () => undefined });

  const occupied: string[] = [];
  for (const table of tables) {
    const [{ count }] = await target`select count(*)::int as count from ${target(table.name)}`;
    if (count > 0) occupied.push(`${table.name} (${count})`);
  }
  if (occupied.length) {
    console.error(`Hedefte dolu tablolar var, durduruldu: ${occupied.join(", ")}`);
    process.exit(1);
  }

  const report: Array<{ table: string; source: number; target: number }> = [];
  for (const table of tables) {
    const [sourceColumnRows] = await source.query<mysql.RowDataPacket[]>("SELECT COLUMN_NAME AS name FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ?", [table.name]);
    const sourceColumns = new Set(sourceColumnRows.map((row) => String(row.name)));
    if (!sourceColumns.size) {
      console.warn(`${table.name}: kaynakta yok, atlandı`);
      report.push({ table: table.name, source: 0, target: 0 });
      continue;
    }
    const columns = table.columns.filter((column) => sourceColumns.has(column));
    const skipped = table.columns.filter((column) => !sourceColumns.has(column));
    const [[{ total }]] = await source.query<mysql.RowDataPacket[]>(`SELECT COUNT(*) AS total FROM \`${table.name}\``);
    const sourceCount = Number(total);
    let copied = 0;
    const orderBy = table.hasId ? "ORDER BY `id`" : "";
    for (let offset = 0; offset < sourceCount; offset += BATCH) {
      const [rows] = await source.query<mysql.RowDataPacket[]>(`SELECT ${columns.map((column) => `\`${column}\``).join(", ")} FROM \`${table.name}\` ${orderBy} LIMIT ${BATCH} OFFSET ${offset}`);
      if (!rows.length) break;
      // id kolonları "GENERATED BY DEFAULT AS IDENTITY": açıkça verilen eski id kabul edilir.
      if (!dryRun) await target`insert into ${target(table.name)} ${target(rows as Record<string, unknown>[], columns)}`;
      copied += rows.length;
    }
    if (!dryRun && table.hasId) {
      await target`select setval(pg_get_serial_sequence(${`"${table.name}"`}, 'id'), coalesce((select max(id) from ${target(table.name)}), 0) + 1, false)`;
    }
    const [{ count: targetCount }] = dryRun ? [{ count: copied }] : await target`select count(*)::int as count from ${target(table.name)}`;
    report.push({ table: table.name, source: sourceCount, target: targetCount });
    console.log(`${table.name}: ${sourceCount} → ${targetCount}${skipped.length ? ` (kaynakta olmayan kolonlar: ${skipped.join(", ")})` : ""}`);
  }

  await source.end();
  await target.end();
  const mismatched = report.filter((row) => row.source !== row.target);
  console.log(`\n${report.length} tablo, ${report.reduce((sum, row) => sum + row.target, 0)} satır${dryRun ? " (kuru çalıştırma, yazılmadı)" : ""}.`);
  if (mismatched.length) {
    console.error(`Satır sayısı uyuşmayan tablolar: ${mismatched.map((row) => `${row.table} ${row.source}≠${row.target}`).join(", ")}`);
    process.exit(1);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
